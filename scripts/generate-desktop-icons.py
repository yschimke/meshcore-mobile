#!/usr/bin/env python3
"""Generates the desktop app icons from the Android launcher icon.

Reads the adaptive icon's layers (app/src/main/res/drawable/ic_launcher_{background,foreground}.xml)
and writes:

  desktop-app/icons/meshcore.svg                   the two layers under a rounded square
  desktop-app/src/jvmMain/resources/meshcore.png   512px: Linux installers and the window icon
  desktop-app/icons/meshcore.ico                   Windows
  desktop-app/icons/meshcore.icns                  macOS

Re-run after changing the launcher icon; never hand-edit the output. Needs rsvg-convert (librsvg)
and Pillow.

  scripts/generate-desktop-icons.py
"""

import os
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLES = os.path.join(ROOT, "app/src/main/res/drawable")
ICONS = os.path.join(ROOT, "desktop-app/icons")
RESOURCES = os.path.join(ROOT, "desktop-app/src/jvmMain/resources")  # ships in the jar
NAME = "meshcore"

A = "{http://schemas.android.com/apk/res/android}"

# Adaptive icons are 108dp with the visible 72dp centred; the desktop tile is that 72dp.
TILE = '<rect x="18" y="18" width="72" height="72" rx="13"/>'


def color(value, alpha):
  """Android #RGB/#ARGB/#RRGGBB/#AARRGGBB plus a separate alpha -> (#RRGGBB, opacity)."""
  v = value.lstrip("#")
  if len(v) in (3, 4):
    v = "".join(c * 2 for c in v)
  a = 1.0
  if len(v) == 8:
    a, v = int(v[:2], 16) / 255, v[2:]
  return f"#{v.upper()}", a * float(alpha)


def paths(drawable):
  """The vector drawable's paths as SVG. Only what the launcher layers use: no transforms."""
  root = ET.parse(os.path.join(DRAWABLES, f"{drawable}.xml")).getroot()
  out = []
  for p in root.iter("path"):
    attrs = [f'd="{p.get(A + "pathData")}"']
    fill = p.get(A + "fillColor")
    if fill and fill.startswith("#"):
      c, a = color(fill, p.get(A + "fillAlpha", "1"))
      attrs.append(f'fill="{c}"')
      if a < 1:
        attrs.append(f'fill-opacity="{a:g}"')
    else:
      attrs.append('fill="none"')
    stroke = p.get(A + "strokeColor")
    if stroke and stroke.startswith("#"):
      c, a = color(stroke, p.get(A + "strokeAlpha", "1"))
      attrs.append(f'stroke="{c}" stroke-width="{p.get(A + "strokeWidth", "1")}"')
      if a < 1:
        attrs.append(f'stroke-opacity="{a:g}"')
      for attr, svg_attr in (("strokeLineCap", "stroke-linecap"), ("strokeLineJoin", "stroke-linejoin")):
        if p.get(A + attr):
          attrs.append(f'{svg_attr}="{p.get(A + attr)}"')
    out.append(f"<path {' '.join(attrs)}/>")
  return "".join(out)


def desktop_svg():
  """The visible 72dp under a rounded square, inset on a 1024 canvas the way macOS's icon grid
  insets its 824px tile, so the mark sits at the same size beside other apps on every desktop."""
  inset = 72 * 100 / 824  # 100px of margin at 1024
  lo, span = 18 - inset, 72 + 2 * inset
  body = paths("ic_launcher_background") + paths("ic_launcher_foreground")
  return (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{lo:.2f} {lo:.2f} {span:.2f} {span:.2f}"'
    ' width="1024" height="1024">'
    f'<!-- Generated by scripts/generate-desktop-icons.py from the Android launcher icon. -->'
    f'<clipPath id="tile">{TILE}</clipPath><g clip-path="url(#tile)">{body}</g>'
    "</svg>\n"
  )


def main():
  from PIL import Image

  os.makedirs(ICONS, exist_ok=True)
  os.makedirs(RESOURCES, exist_ok=True)
  svg = os.path.join(ICONS, f"{NAME}.svg")
  with open(svg, "w") as f:
    f.write(desktop_svg())

  png = os.path.join(RESOURCES, f"{NAME}.png")
  subprocess.run(["rsvg-convert", "-w", "512", "-h", "512", svg, "-o", png], check=True)
  with tempfile.TemporaryDirectory() as tmp:
    big = os.path.join(tmp, f"{NAME}-1024.png")
    subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", svg, "-o", big], check=True)
    img = Image.open(big).convert("RGBA")
    img.save(os.path.join(ICONS, f"{NAME}.ico"), sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    img.save(os.path.join(ICONS, f"{NAME}.icns"))

  print(f"Wrote {os.path.relpath(svg, ROOT)}, {os.path.relpath(png, ROOT)} and {NAME}.{{ico,icns}}",
        file=sys.stderr)


if __name__ == "__main__":
  main()
